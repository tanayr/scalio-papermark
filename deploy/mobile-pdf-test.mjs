async function req(route, method = 'GET', body, cookie = admin) {
  const headers = { Origin: base };
  if (cookie) headers.Cookie = cookie;
  if (body && !Buffer.isBuffer(body)) headers['Content-Type'] = 'application/json';
  else if (body) { headers['Content-Type'] = 'application/pdf'; headers['X-File-Name'] = 'Scalio-deck-mobile.pdf'; }
  return fetch(base + route, { method, headers, body: body ? Buffer.isBuffer(body) ? body : JSON.stringify(body) : undefined, redirect: 'manual' });
}
